export function scanProtectedTerms(text: string): string[] {
  const t = ` ${text.toLowerCase()} `;
  return TERMS.filter((term) =>
    new RegExp(`(^|[^a-z])${term.replace(/[.*+?^${}()|[\]\\-]/g, '\\$&')}([^a-z]|$)`).test(t),
  );
}
